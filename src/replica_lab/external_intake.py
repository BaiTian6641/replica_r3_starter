def load_config(path: str | Path) -> tuple[dict[str, Any], str]:
    """Load and validate an intake configuration, returning it and its digest."""
    path = Path(path)
    _require(path.is_file(), f"intake configuration is missing: {path}")
    raw = path.read_bytes()
    try:
        config = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ExternalIntakeError(f"intake configuration is not valid JSON: {error}") from error
    validate_config(config)
    return config, hashlib.sha256(raw).hexdigest()


def _source_files(dataset: Mapping[str, Any]) -> Mapping[str, Any]:
    files = dataset.get("files")
    _require(isinstance(files, dict), "dataset.files must be an object")
    for key in ("annotation", "metadata", "images"):
        item = files.get(key)
        _require(isinstance(item, dict), f"dataset.files.{key} must be an object")
        _require(isinstance(item.get("path"), str) and item["path"],
                 f"dataset.files.{key}.path must be a non-empty string")
        _require(isinstance(item.get("size"), int) and item["size"] > 0,
                 f"dataset.files.{key}.size must be a positive integer")
        _require(_is_sha256(item.get("sha256")),
                 f"dataset.files.{key}.sha256 must be a lowercase sha256")
    return files


def _terms(config: Mapping[str, Any]) -> Mapping[str, Any]:
    terms = config.get("terms")
    _require(isinstance(terms, dict), "terms must be an object")
    _require(terms.get("permitted_use") == "internal_research",
             "terms are not cleared for internal research; admission is blocked")
    _require(terms.get("research_use_only") is True,
             "research-only asset terms must be acknowledged explicitly")
    _require(terms.get("redistribution") == "prohibited",
             "research-only assets must be marked non-redistributable")
    _require(terms.get("commercial_use") is False,
             "research-only assets must exclude commercial use")
    _require(isinstance(terms.get("reviewed_on"), str) and terms["reviewed_on"],
             "terms.reviewed_on is required")
    components = terms.get("components")
    _require(isinstance(components, list) and components,
             "terms.components must be a non-empty list")
    for component in components:
        _require(isinstance(component, dict), "terms.components items must be objects")
        for key in ("name", "terms", "used"):
            _require(isinstance(component.get(key), str) and component[key],
                     f"terms component requires {key}")
    evidence = terms.get("evidence")
    _require(isinstance(evidence, list) and evidence,
             "terms.evidence must record the reviewed card or terms files")
    for item in evidence:
        _require(isinstance(item, dict) and isinstance(item.get("kind"), str),
                 "terms evidence items need a kind")
        _require(_is_sha256(item.get("sha256")),
                 "terms evidence items need a sha256")
    avoidance = terms.get("reserved_family_avoidance")
    _require(isinstance(avoidance, dict), "terms.reserved_family_avoidance is required")
    reserved = avoidance.get("reserved")
    _require(isinstance(reserved, list) and reserved,
             "terms.reserved_family_avoidance.reserved must be non-empty")
    selected = avoidance.get("selected_family")
    _require(isinstance(selected, str) and selected,
             "terms.reserved_family_avoidance.selected_family is required")
    _require(selected not in reserved, "selected family collides with a reserved family")
    _require(selected not in RESERVED_FAMILIES, "selected family is reserved for evaluation")
    return terms


def validate_config(config: Mapping[str, Any]) -> None:
    """Fail closed unless every provenance, terms, split and budget pin is present."""
    _require(isinstance(config, dict), "intake configuration must be an object")
    _require(config.get("format") == CONFIG_FORMAT,
             f"intake configuration format must be {CONFIG_FORMAT}")
    _require(isinstance(config.get("intake_id"), str) and config["intake_id"],
             "intake_id is required")
    dataset = config.get("dataset")
    _require(isinstance(dataset, dict), "dataset must be an object")
    for key in ("id", "family", "split", "shard"):
        _require(isinstance(dataset.get(key), str) and dataset[key],
                 f"dataset.{key} is required")
    _require(dataset["family"] not in RESERVED_FAMILIES,
             f"dataset family {dataset['family']!r} is reserved for evaluation")
    _require(dataset["id"] not in RESERVED_SOURCE_IDS
             and dataset["id"] != "liuhaotian/LLaVA-Instruct-150K",
             f"source {dataset['id']!r} is reserved or blocked")
    _require(_is_revision(dataset.get("revision")),
             "dataset.revision must be a pinned 40-character commit")
    card = dataset.get("card")
    _require(isinstance(card, dict) and isinstance(card.get("path"), str)
             and card["path"], "dataset.card.path is required")
    _require(_is_sha256(card.get("sha256")), "dataset.card.sha256 is required")
    _require(isinstance(card.get("size"), int) and card["size"] > 0,
             "dataset.card.size must be a positive integer")
    _source_files(dataset)
    terms = _terms(config)
    selected_family = terms["reserved_family_avoidance"]["selected_family"]
    _require(selected_family == dataset["family"],
             "terms selected family and dataset family differ")

    sampling = config.get("sampling")
    _require(isinstance(sampling, dict), "sampling must be an object")
    _require(isinstance(sampling.get("seed"), int), "sampling.seed must be an integer")
    _require(isinstance(sampling.get("window_rows"), int) and sampling["window_rows"] > 0,
             "sampling.window_rows must be positive")
    _require(isinstance(sampling.get("window_bytes"), int) and sampling["window_bytes"] > 0,
             "sampling.window_bytes must be positive")
    _require(isinstance(sampling.get("max_window_bytes"), int)
             and sampling["max_window_bytes"] >= sampling["window_bytes"],
             "sampling.max_window_bytes must be at least sampling.window_bytes")
    target_roots = sampling.get("target_roots")
    _require(isinstance(target_roots, int) and target_roots >= len(ROLES),
             "sampling.target_roots must cover every role")
    _require(target_roots <= sampling["window_rows"],
             "sampling.target_roots cannot exceed sampling.window_rows")
    quotas = sampling.get("split_quotas")
    _require(isinstance(quotas, dict), "sampling.split_quotas must be an object")
    _require(tuple(quotas) == ROLES, f"sampling.split_quotas must name {ROLES}")
    for role in ROLES:
        _require(isinstance(quotas[role], int) and quotas[role] > 0,
                 f"sampling.split_quotas.{role} must be positive")
    _require(sum(quotas.values()) == target_roots,
             "sampling.split_quotas must sum to sampling.target_roots")
    _require(isinstance(sampling.get("order"), str) and sampling["order"],
             "sampling.order is required")

    preprocessing = config.get("preprocessing")
    _require(isinstance(preprocessing, dict), "preprocessing must be an object")
    _require(preprocessing.get("version") == PREPROCESSING_VERSION,
             f"preprocessing.version must be {PREPROCESSING_VERSION}")
    for key in ("min_caption_chars", "max_caption_chars"):
        _require(isinstance(preprocessing.get(key), int) and preprocessing[key] > 0,
                 f"preprocessing.{key} must be positive")
    _require(preprocessing["min_caption_chars"] <= preprocessing["max_caption_chars"],
             "caption length bounds are inverted")
    image = preprocessing.get("image")
    _require(isinstance(image, dict), "preprocessing.image must be an object")
    _require(isinstance(image.get("formats"), list) and image["formats"],
             "preprocessing.image.formats must be non-empty")
    _require(isinstance(image.get("min_dimension"), int) and image["min_dimension"] > 0,
             "preprocessing.image.min_dimension must be positive")
    _require(isinstance(image.get("max_dimension"), int)
             and image["max_dimension"] >= image["min_dimension"],
             "preprocessing.image.max_dimension is invalid")
    _require(isinstance(image.get("max_bytes"), int) and image["max_bytes"] > 0,
             "preprocessing.image.max_bytes must be positive")

    admission = config.get("admission")
    _require(isinstance(admission, dict), "admission must be an object")
    _require(isinstance(admission.get("max_central_directory_bytes"), int)
             and admission["max_central_directory_bytes"] > 0,
             "admission.max_central_directory_bytes must be positive")
    patterns = admission.get("forbidden_url_patterns")
    _require(isinstance(patterns, list), "admission.forbidden_url_patterns must be a list")
    for pattern in patterns:
        _require(isinstance(pattern, str), "forbidden URL patterns must be strings")
        try:
            re.compile(pattern, re.IGNORECASE)
        except re.error as error:
            raise ExternalIntakeError(f"invalid forbidden URL pattern {pattern!r}: {error}") from error
    ceiling = admission.get("campaign_disk_ceiling_bytes")
    _require(isinstance(ceiling, int) and 0 < ceiling <= CAMPAIGN_DISK_CEILING_BYTES,
             "admission.campaign_disk_ceiling_bytes exceeds the campaign ceiling")
    budget = admission.get("max_acquired_bytes")
    _require(isinstance(budget, int) and 0 < budget <= ceiling,
             "admission.max_acquired_bytes must be positive and within the ceiling")

    outputs = config.get("outputs")
    _require(isinstance(outputs, dict), "outputs must be an object")
    for key in ("data_root", "report", "raw_dir", "corpus", "rejections", "manifest",
                "manifests_dir"):
        value = outputs.get(key)
        _require(isinstance(value, str) and value, f"outputs.{key} is required")
        _require(not Path(value).is_absolute() and ".." not in Path(value).parts,
                 f"outputs.{key} must be a relative path inside the project")


