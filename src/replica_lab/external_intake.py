def _config_display_path(config_path: str | Path | None, project_root: Path) -> str:
    if config_path is None:
        return "intake-config.json"
    path = Path(config_path).resolve()
    return str(path.relative_to(project_root)) if path.is_relative_to(project_root) else path.name


def _fetch_prefix(source: RangeSource, *, bytes_limit: int, rows_limit: int,
                  max_bytes_limit: int) -> tuple[bytes, list[dict[str, Any]], int]:
    """Fetch a deterministic annotation/metadata prefix, growing only if needed."""
    requested = bytes_limit
    while True:
        length = min(requested, source.size())
        data = source.read(0, length - 1)
        rows = parse_json_array_prefix(data, rows_limit)
        if len(rows) >= rows_limit or length >= source.size() or requested >= max_bytes_limit:
            return data, rows, requested
        requested = min(requested * 2, max_bytes_limit)


def prepare_tranche(config: Mapping[str, Any], *, project_root: str | Path,
                    config_sha256: str, sources: Mapping[str, RangeSource],
                    config_path: str | Path | None = None,
                    data_root: str | Path | None = None,
                    report_path: str | Path | None = None) -> dict[str, Any]:
    """Acquire, inspect, normalize and write one bounded caption tranche."""
    validate_config(config)
    project_root = Path(project_root).resolve()
    paths = _resolve_output(config, project_root)
    if data_root is not None:
        paths["data_root"] = Path(data_root).resolve()
        paths["raw_dir"] = paths["data_root"] / config["outputs"]["raw_dir"]
        paths["corpus"] = paths["data_root"] / config["outputs"]["corpus"]
        paths["rejections"] = paths["data_root"] / config["outputs"]["rejections"]
        paths["manifest"] = paths["data_root"] / config["outputs"]["manifest"]
        paths["manifests_dir"] = paths["data_root"] / config["outputs"]["manifests_dir"]
    if report_path is not None:
        paths["report"] = Path(report_path).resolve()
    paths["data_root"].mkdir(parents=True, exist_ok=True)
    paths["raw_dir"].mkdir(parents=True, exist_ok=True)
    paths["manifests_dir"].mkdir(parents=True, exist_ok=True)
    _write_text_exact(paths["raw_dir"] / ".gitignore", "*\n!.gitignore\n")

    for key in ("card", "annotation", "metadata", "images_zip"):
        _require(key in sources, f"missing acquisition source {key!r}")
    budget = config["admission"]["max_acquired_bytes"]
    meter = {"bytes": 0, "reads": []}
    metered = {key: MeteredSource(sources[key], meter, budget)
               for key in ("card", "annotation", "metadata", "images_zip")}

    dataset = config["dataset"]
    files = dataset["files"]
    if metered["card"].size() <= 0:
        raise ExternalIntakeError("card source is empty")
    card_size = metered["card"].size()
    card_bytes = metered["card"].read(0, card_size - 1)
    card_sha256 = hashlib.sha256(card_bytes).hexdigest()
    _require(card_sha256 == dataset["card"]["sha256"],
             "upstream card digest differs from the reviewed pin")
    _write_exact(paths["raw_dir"] / "card.md", card_bytes)

    annotation_bytes, annotation_rows, annotation_requested = _fetch_prefix(
        metered["annotation"], bytes_limit=config["sampling"]["window_bytes"],
        rows_limit=config["sampling"]["window_rows"],
        max_bytes_limit=config["sampling"]["max_window_bytes"])
    metadata_bytes, metadata_rows, metadata_requested = _fetch_prefix(
        metered["metadata"], bytes_limit=config["sampling"]["window_bytes"],
        rows_limit=config["sampling"]["window_rows"],
        max_bytes_limit=config["sampling"]["max_window_bytes"])
    _require(len(annotation_rows) >= 1 and len(metadata_rows) >= 1,
             "upstream metadata prefixes contain no complete rows")
    annotation_ids = {row.get("id") for row in annotation_rows if isinstance(row, dict)}
    metadata_ids = {row.get("id") for row in metadata_rows if isinstance(row, dict)}
    window_alignment = {
        "annotation_rows": len(annotation_rows),
        "metadata_rows": len(metadata_rows),
        "shared_ids": len(annotation_ids & metadata_ids),
        "annotation_only_ids": len(annotation_ids - metadata_ids),
        "metadata_only_ids": len(metadata_ids - annotation_ids),
        "method": "rows are joined by pinned upstream id, never by list position",
    }
    _write_exact(paths["raw_dir"] / "annotation_prefix.json", annotation_bytes)
    _write_exact(paths["raw_dir"] / "metadata_prefix.json", metadata_bytes)

    zip_size = files["images"]["size"]
    zip_index = RemoteZipIndex.from_source(
        metered["images_zip"], size=zip_size,
        max_cd_bytes=config["admission"].get("max_central_directory_bytes", 64 * 1024**2))
    _write_exact(paths["raw_dir"] / "images_central_directory.bin", zip_index.directory)

    rejections: list[dict[str, Any]] = []
    candidates = _candidate_rows(annotation_rows, metadata_rows, zip_index.entries,
                                 config, rejections)
    _require(len(candidates) >= config["sampling"]["target_roots"],
             f"only {len(candidates)} eligible metadata candidates in the "
             f"{len(annotation_rows)}-row window; refusing a partial tranche")

    slots = _role_slots(config)
    image_constraints = config["preprocessing"]["image"]
    rows: list[dict[str, Any]] = []
    seen_hashes: dict[str, str] = {}
    member_ledger: list[dict[str, Any]] = []
    downloaded = 0
    for candidate in candidates:
        if len(rows) == len(slots):
            break
        downloaded += 1
        try:
            member = zip_index.read_member(
                metered["images_zip"], candidate["upstream_image_path"],
                max_bytes=image_constraints["max_bytes"])
        except AssetRejected as error:
            rejections.append({"format": REJECTION_FORMAT, "stage": "content",
                               "reason": error.code, "detail": error.detail,
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        try:
            inspection = inspect_image_bytes(
                member["data"], image_constraints,
                member_name=candidate["upstream_image_path"])
        except AssetRejected as error:
            rejections.append({"format": REJECTION_FORMAT, "stage": "content",
                               "reason": error.code, "detail": error.detail,
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        if inspection["sha256"] in seen_hashes:
            rejections.append({"format": REJECTION_FORMAT, "stage": "content",
                               "reason": "duplicate_image_sha256",
                               "detail": f"image already admitted as "
                                         f"{seen_hashes[inspection['sha256']]}",
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        inspection["crc32"] = member["crc32"]
        role = slots[len(rows)]
        row = _row_document(candidate, inspection, role=role, config=config)
        rows.append(row)
        seen_hashes[inspection["sha256"]] = candidate["root_image_id"]
        image_name = f"{candidate['upstream_id']}.jpg"
        _write_exact(paths["raw_dir"] / "images" / image_name, member["data"])
        member_ledger.append({"zip_member": candidate["upstream_image_path"],
                              "local_path": f"raw/images/{image_name}",
                              "sha256": inspection["sha256"],
                              "crc32": member["crc32"],
                              "bytes": member["bytes"]})

    _require(len(rows) == len(slots),
             f"only {len(rows)} of {len(slots)} root assets were admitted; "
             "the sampling window is exhausted")
    rows.sort(key=lambda row: (ROLE_ORDER[row["split"]["role"]],
                               row["split"]["assignment_rank"], row["row_id"]))
    leakage = leakage_report(rows)
    forbidden = _forbidden_patterns(config)
    reserved_matches = 0
    for row in rows:
        asset = row["root_asset"]
        for pattern in forbidden:
            if pattern.search(asset["upstream_url"]) or pattern.search(
                    asset["upstream_image_path"]):
                reserved_matches += 1
    _require(reserved_matches == 0,
             "an admitted asset matches a reserved-family URL pattern")
    rejections.sort(key=lambda item: (item["stage"], item.get("source_row_index", -1),
                                      item["reason"]))

    role_manifests = {role: _role_manifest(rows, role, config) for role in ROLES}
    for role, manifest in role_manifests.items():
        _write_text_exact(paths["manifests_dir"] / f"{role}.json", _json_text(manifest))
    corpus_text = "".join(canonical_json(row) + "\n" for row in rows)
    rejection_text = "".join(canonical_json(item) + "\n" for item in rejections)
    _write_text_exact(paths["corpus"], corpus_text)
    _write_text_exact(paths["rejections"], rejection_text)

    declared_annotation = files["annotation"]["sha256"]
    declared_metadata = files["metadata"]["sha256"]
    acquisition = {
        "acquired_bytes": meter["bytes"],
        "budget_bytes": budget,
        "campaign_disk_ceiling_bytes": config["admission"]["campaign_disk_ceiling_bytes"],
        "within_budget": meter["bytes"] <= budget,
        "read_count": len(meter["reads"]),
        "window_alignment": window_alignment,
        "sources": {
            "card": {"identity": metered["card"].identity,
                     "bytes": len(card_bytes), "sha256": card_sha256,
                     "full_sha256_verified": True},
            "annotation": {
                "identity": metered["annotation"].identity,
                "declared_full_sha256": declared_annotation,
                "full_sha256_verified": False,
                "acquired_prefix_bytes": len(annotation_bytes),
                "acquired_prefix_sha256": hashlib.sha256(annotation_bytes).hexdigest(),
                "requested_prefix_bytes": annotation_requested,
                "complete_rows_in_window": len(annotation_rows),
                "bytes_in_window_sha256": hashlib.sha256(
                    canonical_json(annotation_rows[:config["sampling"]["window_rows"]]).encode()
                ).hexdigest(),
            },
            "metadata": {
                "identity": metered["metadata"].identity,
                "declared_full_sha256": declared_metadata,
                "full_sha256_verified": False,
                "acquired_prefix_bytes": len(metadata_bytes),
                "acquired_prefix_sha256": hashlib.sha256(metadata_bytes).hexdigest(),
                "requested_prefix_bytes": metadata_requested,
                "complete_rows_in_window": len(metadata_rows),
                "bytes_in_window_sha256": hashlib.sha256(
                    canonical_json(metadata_rows[:config["sampling"]["window_rows"]]).encode()
                ).hexdigest(),
            },
            "images_zip": {
                "identity": metered["images_zip"].identity,
                "declared_full_sha256": files["images"]["sha256"],
                "declared_size": zip_size,
                "full_sha256_verified": False,
                "central_directory_bytes": zip_index.cd_size,
                "central_directory_offset": zip_index.cd_offset,
                "central_directory_sha256": zip_index.cd_sha256,
                "central_directory_records": zip_index.total_records,
                "file_entries": len(zip_index.entries),
                "members_verified": len(member_ledger),
                "member_verification": "CRC32 and uncompressed size per selected member",
                "members": member_ledger,
            },
        },
        "integrity_note": (
            "Bounded acquisition verifies the full card digest, every selected ZIP "
            "member CRC32/size and every admitted image digest. The full annotation, "
            "metadata and 27.36 GB image archive digests are pinned from the upstream "
            "LFS metadata but intentionally not downloaded in full."),
    }
    counts = {
        "window_rows": len(annotation_rows),
        "metadata_rows": len(metadata_rows),
        "metadata_candidates": len(candidates),
        "inspected_assets": len(rows) + sum(1 for item in rejections
                                            if item["stage"] == "content"),
        "admitted_rows": len(rows),
        "admitted_root_assets": len({row["split"]["group_key"] for row in rows}),
        "normalized_rows": len(rows),
        "rejected_rows": len(rejections),
        "roles": {role: {"rows": sum(1 for row in rows if row["split"]["role"] == role),
                         "root_groups": len({row["split"]["group_key"] for row in rows
                                             if row["split"]["role"] == role})}
                  for role in ROLES},
        "rejection_reasons": dict(sorted(Counter(
            item["reason"] for item in rejections).items())),
    }
    inspection = {
        "assets": len(rows),
        "decode_verified": sum(1 for row in rows
                               if row["provenance"]["image_inspection"]["decode_verified"]),
        "structural_verified": sum(1 for row in rows
                                   if row["provenance"]["image_inspection"]["structural_verified"]),
        "decoders": dict(sorted(Counter(
            row["provenance"]["image_inspection"]["decoder"] for row in rows).items())),
        "formats": dict(sorted(Counter(row["root_asset"]["image_format"]
                                       for row in rows).items())),
        "image_bytes": sum(row["root_asset"]["image_bytes"] for row in rows),
    }
    artifacts = {
        "corpus": {"path": str(paths["corpus"].relative_to(paths["data_root"])),
                   "sha256": hashlib.sha256(corpus_text.encode()).hexdigest(),
                   "rows": len(rows)},
        "rejections": {"path": str(paths["rejections"].relative_to(paths["data_root"])),
                       "sha256": hashlib.sha256(rejection_text.encode()).hexdigest(),
                       "rows": len(rejections)},
        "manifests": {role: {
            "path": str((paths["manifests_dir"] / f"{role}.json").relative_to(paths["data_root"])),
            "sha256": hashlib.sha256(_json_text(role_manifests[role]).encode()).hexdigest(),
            "rows": len(role_manifests[role]["rows"]),
            "sealed": role_manifests[role]["sealed"],
            "seal_sha256": role_manifests[role].get("seal_sha256"),
        } for role in ROLES},
    }
    exclusions = {
        "window": {"rows": len(annotation_rows),
                   "bytes": len(annotation_bytes),
                   "scope": config["dataset"]["shard"]},
        "rows_outside_window": {
            "inspected": False,
            "reason": ("bounded deterministic window over the pinned upstream array; "
                       "outside rows were never downloaded and are not claimed as "
                       "quality rejections"),
        },
        "metadata_candidates": len(candidates),
        "downloaded_assets": downloaded,
        "admitted_assets": len(rows),
        "candidates_beyond_quota": len(candidates) - downloaded,
        "rejected": {
            "rows": len(rejections),
            "metadata": sum(1 for item in rejections if item["stage"] == "metadata"),
            "content": sum(1 for item in rejections if item["stage"] == "content"),
            "reasons": counts["rejection_reasons"],
            "ledger": artifacts["rejections"],
        },
    }
    manifest = {
        "format": TRANCHE_FORMAT,
        "intake_id": config["intake_id"],
        "status": "admitted",
        "created_on": config.get("created_on"),
        "config": {"path": _config_display_path(config_path, project_root),
                   "sha256": config_sha256},
        "dataset": {
            "id": dataset["id"],
            "revision": dataset["revision"],
            "family": dataset["family"],
            "split": dataset["split"],
            "shard": dataset["shard"],
            "source_url": dataset.get("source_url"),
            "composition_note": dataset.get("composition_note"),
            "card": dataset["card"],
            "files": files,
        },
        "terms": config["terms"],
        "sampling": {key: config["sampling"][key] for key in
                     ("seed", "order", "window_bytes", "max_window_bytes",
                      "window_rows", "target_roots", "split_quotas")},
        "preprocessing": config["preprocessing"],
        "counts": counts,
        "exclusions": exclusions,
        "inspection": inspection,
        "reserved_family_check": {
            "patterns": config["admission"]["forbidden_url_patterns"],
            "admitted_asset_matches": reserved_matches,
            "reserved_families": config["terms"]["reserved_family_avoidance"]["reserved"],
        },
        "acquisition": acquisition,
        "leakage": leakage,
        "artifacts": artifacts,
        "assets": [{
            "root_image_id": row["root_asset"]["root_image_id"],
            "role": row["split"]["role"],
            "group_key": row["split"]["group_key"],
            "upstream_image_path": row["root_asset"]["upstream_image_path"],
            "upstream_url": row["root_asset"]["upstream_url"],
            "zip_member": row["root_asset"]["zip_member"],
            "zip_member_crc32": row["root_asset"]["zip_member_crc32"],
            "image_sha256": row["root_asset"]["image_sha256"],
            "image_bytes": row["root_asset"]["image_bytes"],
            "format": row["root_asset"]["image_format"],
            "width": row["root_asset"]["width"],
            "height": row["root_asset"]["height"],
            "row_id": row["row_id"],
            "row_sha256": _row_sha256(row),
        } for row in rows],
    }
    _write_text_exact(paths["manifest"], _json_text(manifest))
    report = {
        "format": REPORT_FORMAT,
        "status": manifest["status"],
        "intake_id": config["intake_id"],
        "manifest": str(paths["manifest"]),
        "manifest_sha256": hashlib.sha256(_json_text(manifest).encode()).hexdigest(),
        "dataset": {"id": dataset["id"], "revision": dataset["revision"],
                    "family": dataset["family"], "split": dataset["split"],
                    "shard": dataset["shard"],
                    "composition_note": dataset.get("composition_note")},
        "config": manifest["config"],
        "counts": counts,
        "exclusions": exclusions,
        "inspection": inspection,
        "reserved_family_check": manifest["reserved_family_check"],
        "artifacts": artifacts,
        "acquired_bytes": acquisition["acquired_bytes"],
        "budget_bytes": budget,
        "terms": {key: config["terms"][key] for key in
                  ("permitted_use", "research_use_only", "redistribution",
                   "commercial_use", "reviewed_on")},
        "leakage": leakage,
        "claim": "Corpus preparation only; no model training or capability claim.",
    }
    _write_text_exact(paths["report"], _json_text(report))
    return manifest


