def _probe_jpeg(data: bytes) -> dict[str, Any]:
    _require(data.startswith(b"\xff\xd8"), "JPEG start-of-image marker is missing")
    _require(data.endswith(b"\xff\xd9"), "JPEG end-of-image marker is missing")
    index = 2
    width = height = None
    channels = None
    scan_started = False
    while index < len(data) - 1:
        _require(data[index] == 0xFF, "JPEG marker alignment is invalid")
        while index < len(data) and data[index] == 0xFF:
            index += 1
        _require(index < len(data), "JPEG marker is truncated")
        marker = data[index]
        index += 1
        if marker == 0xD9:
            break
        if marker in (0x01,) or 0xD0 <= marker <= 0xD7:
            continue
        _require(index + 2 <= len(data), "JPEG segment length is truncated")
        length = struct.unpack(">H", data[index:index + 2])[0]
        _require(length >= 2, "JPEG segment length is invalid")
        segment_end = index + length
        _require(segment_end <= len(data), "JPEG segment extends beyond the file")
        if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7,
                      0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            _require(length >= 8, "JPEG frame header is truncated")
            precision = data[index + 2]
            height, width = struct.unpack(">HH", data[index + 3:index + 7])
            channels = data[index + 7]
            _require(precision == 8, f"unsupported JPEG precision {precision}")
        if marker == 0xDA:
            _require(width is not None, "JPEG scan precedes the frame header")
            _require(length >= 3, "JPEG scan header is truncated")
            entropy_start = segment_end
            _require(entropy_start < len(data) - 2,
                     "JPEG scan carries no entropy-coded data")
            scan_started = True
            break
        index = segment_end
    _require(width is not None and height is not None,
             "JPEG frame header is missing")
    _require(scan_started, "JPEG scan header is missing")
    return {"format": "JPEG", "width": width, "height": height, "channels": channels,
            "structural_verified": True}


def _probe_png(data: bytes) -> dict[str, Any]:
    _require(data.startswith(b"\x89PNG\r\n\x1a\n"), "PNG signature is invalid")
    index = 8
    width = height = None
    saw_end = False
    while index + 12 <= len(data):
        length = struct.unpack(">I", data[index:index + 4])[0]
        chunk_type = data[index + 4:index + 8]
        body_end = index + 8 + length
        _require(body_end + 4 <= len(data), "PNG chunk is truncated")
        body = data[index + 8:body_end]
        crc = struct.unpack(">I", data[body_end:body_end + 4])[0]
        _require((zlib.crc32(chunk_type + body) & 0xFFFFFFFF) == crc,
                 "PNG chunk CRC mismatch")
        if chunk_type == b"IHDR":
            _require(length == 13, "PNG IHDR chunk has the wrong size")
            width, height = struct.unpack(">II", body[0:8])
            _require(width > 0 and height > 0, "PNG dimensions are invalid")
        if chunk_type == b"IEND":
            saw_end = True
            index = body_end + 4
            break
        index = body_end + 4
    _require(width is not None and height is not None, "PNG IHDR chunk is missing")
    _require(saw_end, "PNG IEND chunk is missing")
    _require(index == len(data), "PNG has trailing bytes after IEND")
    return {"format": "PNG", "width": width, "height": height, "channels": None,
            "structural_verified": True}


def _probe_webp(data: bytes) -> dict[str, Any]:
    _require(len(data) >= 30 and data[:4] == b"RIFF" and data[8:12] == b"WEBP",
             "WebP header is invalid")
    riff_size = struct.unpack("<I", data[4:8])[0]
    _require(riff_size + 8 == len(data), "WebP RIFF size differs from the file")
    kind = data[12:16]
    if kind == b"VP8X":
        width = 1 + int.from_bytes(data[24:27], "little")
        height = 1 + int.from_bytes(data[27:30], "little")
    elif kind == b"VP8 ":
        _require(data[23:26] == b"\x9d\x01\x2a", "WebP VP8 frame header is invalid")
        width = struct.unpack("<H", data[26:28])[0] & 0x3FFF
        height = struct.unpack("<H", data[28:30])[0] & 0x3FFF
    elif kind == b"VP8L":
        _require(data[20] == 0x2F, "WebP VP8L signature is invalid")
        packed = int.from_bytes(data[21:25], "little")
        width = (packed & 0x3FFF) + 1
        height = ((packed >> 14) & 0x3FFF) + 1
    else:
        raise AssetRejected("image_unsupported_format", f"unknown WebP chunk {kind!r}")
    return {"format": "WEBP", "width": width, "height": height, "channels": None,
            "structural_verified": True}


def _pillow_check(data: bytes, declared: Mapping[str, Any]) -> dict[str, Any]:
    try:
        from PIL import Image  # type: ignore
    except ImportError:
        return {"decode_verified": False, "decoder": "structural-only"}
    try:
        with Image.open(io.BytesIO(data)) as image:
            image.load()
            if (image.size[0], image.size[1]) != (declared["width"], declared["height"]):
                raise AssetRejected("image_decode_failed",
                                    "decoded dimensions differ from the header")
            mode = image.mode
        return {"decode_verified": True,
                "decoder": f"pillow-{getattr(Image, '__version__', 'unknown')}",
                "decoded_mode": mode}
    except AssetRejected:
        raise
    except Exception as error:  # Pillow raises many decoder-specific classes
        raise AssetRejected("image_decode_failed", str(error)) from error


def inspect_image_bytes(data: bytes, image_constraints: Mapping[str, Any],
                        *, member_name: str = "") -> dict[str, Any]:
    """Structurally verify an image and optionally decode it with Pillow."""
    if not isinstance(data, bytes) or not data:
        raise AssetRejected("invalid_image", "image bytes are empty")
    if len(data) > image_constraints["max_bytes"]:
        raise AssetRejected("image_too_large",
                            f"image is {len(data)} bytes; bound is "
                            f"{image_constraints['max_bytes']}")
    try:
        if data.startswith(b"\xff\xd8"):
            info = _probe_jpeg(data)
        elif data.startswith(b"\x89PNG\r\n\x1a\n"):
            info = _probe_png(data)
        elif data.startswith(b"RIFF") and data[8:12] == b"WEBP":
            info = _probe_webp(data)
        else:
            raise AssetRejected("image_unsupported_format",
                                "bytes are not a supported image signature")
    except AssetRejected:
        raise
    except ExternalIntakeError as error:
        raise AssetRejected("invalid_image", str(error)) from error
    if info["format"] not in image_constraints["formats"]:
        raise AssetRejected("image_unsupported_format",
                            f"{info['format']} is not enabled")
    for key in ("width", "height"):
        value = info[key]
        if not image_constraints["min_dimension"] <= value <= image_constraints["max_dimension"]:
            raise AssetRejected(
                "image_dimensions_out_of_bounds",
                f"{key}={value} outside "
                f"[{image_constraints['min_dimension']}, {image_constraints['max_dimension']}]")
    if member_name and image_constraints.get("require_extension_match"):
        suffix = Path(member_name).suffix.lower().lstrip(".")
        expected = {"JPEG": "jpg"}.get(info["format"], info["format"].lower())
        if suffix not in {expected, "jpeg" if expected == "jpg" else expected}:
            raise AssetRejected("image_extension_mismatch",
                                f"{member_name} declares {suffix}, content is {info['format']}")
    info["sha256"] = hashlib.sha256(data).hexdigest()
    info["bytes"] = len(data)
    info.update(_pillow_check(data, info))
    return info


