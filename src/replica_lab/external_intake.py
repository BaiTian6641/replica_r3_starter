def _zip64_extra(extra: bytes, needs: Sequence[bool]) -> list[int]:
    offset = 0
    values: list[int] = []
    while offset + 4 <= len(extra):
        header_id, length = struct.unpack("<HH", extra[offset:offset + 4])
        body = extra[offset + 4:offset + 4 + length]
        _require(len(body) == length, "truncated ZIP extra field")
        if header_id == 0x0001:
            cursor = 0
            for needed, width in zip(needs, (8, 8, 8)):
                if not needed:
                    continue
                _require(cursor + width <= len(body), "truncated ZIP64 extra field")
                values.append(struct.unpack("<Q", body[cursor:cursor + width])[0])
                cursor += width
            break
        offset += 4 + length
    _require(len(values) == sum(needs), "ZIP64 extra field lacks required values")
    return values


def _find_eocd(tail: bytes) -> int:
    index = tail.rfind(b"PK\x05\x06")
    _require(index >= 0, "ZIP end-of-central-directory record is missing")
    _require(index + 22 <= len(tail), "ZIP end-of-central-directory record is truncated")
    return index


class RemoteZipIndex:
    """Central-directory index for a large remote ZIP archive.

    Only the directory and selected members are fetched; the archive itself is
    never mirrored. Per-member CRC32 and sizes are verified after extraction.
    """

    def __init__(self, entries: Mapping[str, dict[str, Any]], *, cd_size: int,
                 cd_offset: int, cd_sha256: str, comment: str, directory: bytes,
                 total_records: int):
        self.entries = dict(entries)
        self.total_records = total_records
        self.cd_size = cd_size
        self.cd_offset = cd_offset
        self.cd_sha256 = cd_sha256
        self.comment = comment
        self.directory = directory

    @classmethod
    def from_source(cls, source: RangeSource, *, size: int,
                    max_cd_bytes: int) -> "RemoteZipIndex":
        _require(size > 0, "ZIP size must be positive")
        tail_length = min(size, 131072)
        tail = source.read(size - tail_length, size - 1)
        eocd_offset = _find_eocd(tail)
        eocd = struct.unpack("<4s4H2LH", tail[eocd_offset:eocd_offset + 22])
        _, disk, cd_disk, entries_disk, entries_total, cd_size, cd_offset, comment_length = eocd
        if (entries_total == 0xFFFF or cd_size == 0xFFFFFFFF or cd_offset == 0xFFFFFFFF):
            locator = tail.rfind(b"PK\x06\x07")
            _require(locator >= 0, "ZIP64 locator is missing")
            locator_record = struct.unpack("<4sLQL", tail[locator:locator + 20])
            zip64_offset = locator_record[2]
            if zip64_offset >= size - tail_length:
                zip64_record = source.read(zip64_offset, zip64_offset + 55)
            else:
                local = zip64_offset - (size - tail_length)
                zip64_record = tail[local:local + 56]
            _require(len(zip64_record) == 56, "ZIP64 end-of-central-directory record is truncated")
            _, record_size, _, _, disk, cd_disk, entries_disk, entries_total, cd_size, cd_offset = \
                struct.unpack("<4sQ2H2L4Q", zip64_record)
            _require(record_size >= 44, "unexpected ZIP64 end record size")
        _require(disk == 0 and cd_disk == 0 and entries_disk == entries_total,
                 "multi-disk ZIP archives are not admitted")
        _require(entries_total > 0, "ZIP archive is empty")
        _require(cd_size > 0 and cd_offset >= 0, "ZIP central directory is missing")
        _require(cd_size <= max_cd_bytes,
                 f"ZIP central directory ({cd_size} bytes) exceeds the reviewed bound")
        _require(cd_offset + cd_size <= size, "ZIP central directory lies outside the archive")
        directory = source.read(cd_offset, cd_offset + cd_size - 1)
        cd_digest = hashlib.sha256(directory).hexdigest()
        entries: dict[str, dict[str, Any]] = {}
        index = 0
        total_seen = 0
        while index + 46 <= len(directory):
            _require(directory[index:index + 4] == b"PK\x01\x02",
                     "ZIP central directory entry signature is invalid")
            fields = struct.unpack("<4s6H3L5H2L", directory[index:index + 46])
            flags, method = fields[3], fields[4]
            crc, compressed, uncompressed = fields[7], fields[8], fields[9]
            name_length, extra_length, comment_len = fields[10], fields[11], fields[12]
            offset = fields[16]
            name_start = index + 46
            name_end = name_start + name_length
            extra_end = name_end + extra_length
            _require(extra_end + comment_len <= len(directory), "truncated ZIP directory entry")
            raw_extra = directory[name_end:extra_end]
            name = directory[name_start:name_end].decode("utf-8", "strict")
            total_seen += 1
            if name.endswith("/"):
                index = extra_end + comment_len
                continue
            needs = (uncompressed == 0xFFFFFFFF, compressed == 0xFFFFFFFF,
                     offset == 0xFFFFFFFF)
            if any(needs):
                values = _zip64_extra(raw_extra, needs)
                cursor = 0
                if needs[0]:
                    uncompressed = values[cursor]
                    cursor += 1
                if needs[1]:
                    compressed = values[cursor]
                    cursor += 1
                if needs[2]:
                    offset = values[cursor]
            _require(not (flags & 0x1), f"encrypted ZIP member is not admitted: {name}")
            _require(method in (0, 8), f"unsupported ZIP compression for {name}")
            _require(name not in entries, f"duplicate ZIP member name: {name}")
            _require(0 <= offset < size, f"ZIP member offset is outside the archive: {name}")
            entries[name] = {"name": name, "method": method, "crc32": crc,
                             "compressed_bytes": compressed, "bytes": uncompressed,
                             "offset": offset}
            index = extra_end + comment_len
        _require(index == len(directory), "ZIP central directory has trailing bytes")
        _require(total_seen == entries_total,
                 f"ZIP directory entry count differs ({total_seen} != {entries_total})")
        comment = tail[eocd_offset + 22:eocd_offset + 22 + comment_length].decode(
            "utf-8", "replace")
        return cls(entries, cd_size=cd_size, cd_offset=cd_offset,
                   cd_sha256=cd_digest, comment=comment, directory=directory,
                   total_records=total_seen)

    def read_member(self, source: RangeSource, name: str, *,
                    max_bytes: int) -> dict[str, Any]:
        entry = self.entries.get(name)
        _require(entry is not None, f"ZIP member is missing: {name}")
        _require(0 < entry["bytes"] <= max_bytes,
                 f"ZIP member {name} is {entry['bytes']} bytes; bound is {max_bytes}")
        header = source.read(entry["offset"], entry["offset"] + 29)
        fields = struct.unpack("<4s5H3L2H", header)
        _require(fields[0] == b"PK\x03\x04", f"ZIP local header is invalid: {name}")
        _require(not (fields[2] & 0x1), f"encrypted ZIP member is not admitted: {name}")
        _require(fields[3] == entry["method"],
                 f"ZIP local compression method differs for {name}")
        name_length, extra_length = fields[9], fields[10]
        name_start = entry["offset"] + 30
        local_name = source.read(name_start, name_start + name_length - 1)
        _require(local_name.decode("utf-8") == name, f"ZIP local name differs: {name}")
        data_start = name_start + name_length + extra_length
        compressed = source.read(data_start, data_start + entry["compressed_bytes"] - 1)
        _require(len(compressed) == entry["compressed_bytes"],
                 f"short ZIP member read: {name}")
        if entry["method"] == 8:
            try:
                data = zlib.decompress(compressed, -15)
            except zlib.error as error:
                raise ExternalIntakeError(f"ZIP member inflate failed for {name}: {error}") from error
        else:
            data = compressed
        _require(len(data) == entry["bytes"],
                 f"ZIP member size differs for {name}: {len(data)} != {entry['bytes']}")
        _require((zlib.crc32(data) & 0xFFFFFFFF) == entry["crc32"],
                 f"ZIP member CRC32 mismatch for {name}; refusing tampered bytes")
        return {"name": name, "data": data, "sha256": hashlib.sha256(data).hexdigest(),
                "crc32": f"{entry['crc32']:08x}", "bytes": len(data)}


