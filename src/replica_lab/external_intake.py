"""Bounded external image-caption intake with provenance and split controls.

The intake admits a small, reviewable slice of a pinned upstream caption/grounding
source. It never trusts a catalogue record alone: the card, annotation prefix,
image archive directory and every admitted image are inspected, hashed and
recorded. Gold captions are kept in ``target`` records and are never copied into
``observation`` inputs. Complete root assets and their derivatives share one
split; the final-evaluation split is sealed and untouched by development.

Failure is closed: missing pins, unresolved terms, reserved-family conflicts,
duplicate roots, tampering, an overrun budget or an unreadable image all refuse
admission instead of substituting owned procedural data.
"""
