def _observation_text(row: Mapping[str, Any]) -> str:
    return canonical_json(row["observation"])


def assert_row_label_separation(row: Mapping[str, Any]) -> None:
    """Gold labels must never appear in observation inputs."""
    _require(isinstance(row.get("observation"), dict), "row observation must be an object")
    _require(isinstance(row.get("target"), dict), "row target must be an object")
    for forbidden in ("caption", "target", "answer", "gold", "label"):
        _require(forbidden not in row["observation"],
                 f"observation must not expose a {forbidden!r} field")
    caption = row["target"].get("caption")
    _require(isinstance(caption, str) and caption, "row target caption is missing")
    observation_text = _observation_text(row).casefold()
    _require(caption.casefold() not in observation_text,
             "gold caption appears inside the observation input")
    for value in row["observation"].values():
        _require(not (isinstance(value, str) and value.casefold() == caption.casefold()),
                 "an observation field equals the gold caption")
    prompt = row["observation"].get("prompt")
    _require(isinstance(prompt, str) and prompt, "observation prompt is missing")


def _row_sha256(row: Mapping[str, Any]) -> str:
    return sha256_text(canonical_json(row))


def leakage_report(rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Fail closed on any root, image, caption or prompt crossing splits."""
    _require(rows, "no rows to check")
    group_roles: dict[str, str] = {}
    group_images: dict[str, str] = {}
    image_roles: dict[str, str] = {}
    caption_roles: dict[str, str] = {}
    id_roles: dict[str, str] = {}
    for row in rows:
        assert_row_label_separation(row)
        role = row["split"]["role"]
        _require(role in ROLES, f"unknown split role {role!r}")
        group = row["split"]["group_key"]
        _require(group == row["root_asset"]["root_image_id"],
                 "split group key must equal the root image id")
        previous_image = group_images.get(group)
        _require(previous_image is None
                 or previous_image == row["root_asset"]["image_sha256"],
                 f"root group {group!r} maps to more than one image digest")
        group_images[group] = row["root_asset"]["image_sha256"]
        for table, key, label in ((group_roles, group, "root group"),
                                  (image_roles, row["root_asset"]["image_sha256"], "image"),
                                  (caption_roles, row["target"]["caption"].casefold(),
                                   "caption"),
                                  (id_roles, row["row_id"], "row id")):
            existing = table.get(key)
            _require(existing is None or existing == role,
                     f"{label} {key!r} crosses splits: {existing} and {role}")
            table[key] = role
    eval_image_hashes = {image for image, role in image_roles.items() if role == EVAL_ROLE}
    train_image_hashes = {image for image, role in image_roles.items() if role != EVAL_ROLE}
    eval_captions = {caption for caption, role in caption_roles.items() if role == EVAL_ROLE}
    train_captions = {caption for caption, role in caption_roles.items() if role != EVAL_ROLE}
    _require(not (eval_image_hashes & train_image_hashes),
             "final-evaluation images overlap development or training images")
    _require(not (eval_captions & train_captions),
             "final-evaluation captions overlap development or training captions")
    observations: dict[str, list[str]] = {role: [] for role in ROLES}
    for row in rows:
        observations[row["split"]["role"]].append(
            canonical_json(row["observation"]).casefold())
    for row in rows:
        caption = row["target"]["caption"].casefold()
        for role in ROLES:
            if role == row["split"]["role"]:
                continue
            for observation in observations[role]:
                _require(caption not in observation,
                         "a gold caption appears in another split's observation input")
    return {
        "root_groups_disjoint": True,
        "image_hashes_disjoint": True,
        "caption_hashes_disjoint": True,
        "observation_caption_leakage_cross_split": 0,
        "row_ids_unique": True,
        "label_separation_verified": True,
        "eval_vs_non_eval_image_overlap": 0,
        "eval_vs_non_eval_caption_overlap": 0,
    }


