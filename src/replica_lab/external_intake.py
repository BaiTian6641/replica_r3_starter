# Upstream JSON prefixes


def parse_json_array_prefix(data: bytes, max_rows: int) -> list[dict[str, Any]]:
    """Read complete objects from the prefix of a pretty-printed JSON array.

    A truncated final object is discarded rather than guessed. Non-object rows
    are returned so the caller can reject them explicitly.
    """
    _require(max_rows > 0, "max_rows must be positive")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise ExternalIntakeError(f"upstream JSON prefix is not UTF-8: {error}") from error
    decoder = json.JSONDecoder()
    start = 0
    while start < len(text) and text[start] != "[":
        _require(text[start] in " \r\n\t", "upstream JSON does not start with an array")
        start += 1
    _require(start < len(text) and text[start] == "[", "upstream JSON array is missing")
    rows: list[dict[str, Any]] = []
    index = start + 1
    while index < len(text) and len(rows) < max_rows:
        while index < len(text) and text[index] in " \r\n\t,":
            index += 1
        if index >= len(text) or text[index] == "]":
            break
        try:
            value, next_index = decoder.raw_decode(text, index)
        except json.JSONDecodeError:
            break
        _require(isinstance(value, dict), "upstream JSON array rows must be objects")
        rows.append(value)
        index = next_index
    return rows


