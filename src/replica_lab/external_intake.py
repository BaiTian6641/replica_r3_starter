class RangeSource:
    """Inclusive byte-range reader with a stable identity."""

    identity: str = ""

    def read(self, start: int, end: int) -> bytes:  # pragma: no cover - interface
        raise NotImplementedError

    def size(self) -> int:  # pragma: no cover - interface
        raise NotImplementedError


class FileRangeSource(RangeSource):
    """Local byte-range reader used by fixtures and offline review."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        _require(self.path.is_file(), f"local source is missing: {self.path}")
        self.identity = f"file:{self.path}"

    def size(self) -> int:
        return self.path.stat().st_size

    def read(self, start: int, end: int) -> bytes:
        size = self.size()
        _require(0 <= start <= end < size,
                 f"range {start}-{end} lies outside {self.path.name} ({size} bytes)")
        with self.path.open("rb") as stream:
            stream.seek(start)
            data = stream.read(end - start + 1)
        _require(len(data) == end - start + 1, "short local range read")
        return data


class HttpRangeSource(RangeSource):
    """HTTPS range reader for a pinned dataset file."""

    def __init__(self, url: str, *, size: int, timeout: float = 120.0,
                 retries: int = 5, user_agent: str = "replica-external-intake/1"):
        _require(url.startswith("https://"), "only HTTPS upstream sources are admitted")
        _require(isinstance(size, int) and size > 0, "upstream size must be positive")
        self.url = url
        self.identity = url
        self._size = size
        self.timeout = timeout
        self.retries = retries
        self.user_agent = user_agent

    def size(self) -> int:
        return self._size

    def read(self, start: int, end: int) -> bytes:
        _require(0 <= start <= end < self._size,
                 f"range {start}-{end} lies outside upstream file ({self._size} bytes)")
        last_error: Exception | None = None
        for attempt in range(self.retries):
            request = urlrequest.Request(
                self.url, headers={"Range": f"bytes={start}-{end}",
                                   "User-Agent": self.user_agent})
            try:
                with urlrequest.urlopen(request, timeout=self.timeout) as response:
                    data = response.read()
                    status = response.status
                    content_range = response.headers.get("Content-Range", "")
                _require(status == 206, f"upstream did not honour the range request ({status})")
                _require(len(data) == end - start + 1,
                         f"short upstream range read: {len(data)} of {end - start + 1} bytes")
                if content_range:
                    _require(content_range.startswith(f"bytes {start}-{end}/"),
                             f"upstream range mismatch: {content_range}")
                return data
            except (urlerror.HTTPError, urlerror.URLError, TimeoutError,
                    ExternalIntakeError) as error:
                last_error = error
                status = getattr(error, "code", None)
                retryable = status in (400, 408, 425, 429, 500, 502, 503, 504)
                if isinstance(error, urlerror.URLError) or retryable:
                    time.sleep(0.25 * (attempt + 1))
                    continue
                raise
        raise ExternalIntakeError(
            f"upstream range read failed after {self.retries} attempts: {last_error}")


class MeteredSource:
    """Count every acquired byte and refuse to cross the configured budget."""

    def __init__(self, source: RangeSource, meter: dict[str, Any], max_bytes: int):
        self.source = source
        self.meter = meter
        self.max_bytes = max_bytes
        self.identity = source.identity

    def read(self, start: int, end: int) -> bytes:
        requested = end - start + 1
        _require(requested > 0, "empty range request")
        _require(self.meter["bytes"] + requested <= self.max_bytes,
                 "acquisition budget would be exceeded; refusing the read")
        data = self.source.read(start, end)
        self.meter["bytes"] += len(data)
        self.meter["reads"].append({"source": self.identity, "start": start,
                                    "end": end, "bytes": len(data)})
        return data

    def size(self) -> int:
        return self.source.size()


