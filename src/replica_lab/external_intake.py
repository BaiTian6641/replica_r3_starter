def verify_tranche(data_root: str | Path, *, config: Mapping[str, Any] | None = None,
                   config_sha256: str | None = None,
                   require_images: bool = True) -> dict[str, Any]:
    """Re-verify an admitted tranche byte-for-byte; refuse any tampering."""
    data_root = Path(data_root)
    manifest_path = data_root / "manifest.json"
    _require(manifest_path.is_file(), f"tranche manifest is missing: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    _require(manifest.get("format") == TRANCHE_FORMAT, "tranche manifest format differs")
    _require(manifest.get("status") == "admitted", "tranche is not admitted")
    if config is not None:
        validate_config(config)
        expected = config_sha256
        _require(expected is not None, "config digest is required for verification")
        _require(manifest["config"]["sha256"] == expected,
                 "tranche was built from a different intake configuration")
        _require(manifest["dataset"]["id"] == config["dataset"]["id"],
                 "tranche dataset differs from the configuration")
        _require(manifest["dataset"]["revision"] == config["dataset"]["revision"],
                 "tranche revision differs from the configuration")
        _require(manifest["preprocessing"]["version"] == config["preprocessing"]["version"],
                 "tranche preprocessing version differs")
        _require(manifest["reserved_family_check"]["patterns"]
                 == config["admission"]["forbidden_url_patterns"],
                 "tranche reserved-family patterns differ from the configuration")
        _require(manifest["reserved_family_check"]["admitted_asset_matches"] == 0,
                 "tranche admitted an asset from a reserved family")
    corpus_path = data_root / manifest["artifacts"]["corpus"]["path"]
    _require(corpus_path.is_file(), "normalized corpus is missing")
    corpus_bytes = corpus_path.read_bytes()
    _require(hashlib.sha256(corpus_bytes).hexdigest()
             == manifest["artifacts"]["corpus"]["sha256"],
             "normalized corpus digest differs from the manifest")
    rows = [json.loads(line) for line in corpus_bytes.decode("utf-8").splitlines() if line]
    _require(len(rows) == manifest["artifacts"]["corpus"]["rows"],
             "normalized corpus row count differs from the manifest")
    for row in rows:
        _require(row.get("format") == ROW_FORMAT, "normalized row format differs")
        assert_row_label_separation(row)
        role = row["split"]["role"]
        _require(ROLE_ORDER.get(role) is not None, "normalized row has an unknown role")
        _require(row["source"]["revision"] == manifest["dataset"]["revision"],
                 "row revision differs from the tranche pin")
        _require(row["provenance"]["preprocessing_version"]
                 == manifest["preprocessing"]["version"],
                 "row preprocessing version differs")
    leakage = leakage_report(rows)
    _require(leakage == manifest["leakage"], "stored leakage report does not match")
    acquisition = manifest.get("acquisition", {})
    _require(acquisition.get("within_budget") is True,
             "tranche acquisition ledger is not within budget")
    _require(isinstance(acquisition.get("acquired_bytes"), int)
             and acquisition["acquired_bytes"] <= acquisition.get("budget_bytes", 0),
             "tranche acquired-byte ledger is inconsistent")
    _require(acquisition["acquired_bytes"] <= acquisition["budget_bytes"],
             "tranche exceeded its acquisition budget")
    zip_ledger = acquisition.get("sources", {}).get("images_zip", {})
    members = zip_ledger.get("members", [])
    _require(len(members) == len(rows), "image member ledger does not cover every row")
    _require({item["sha256"] for item in members}
             == {row["root_asset"]["image_sha256"] for row in rows},
             "image member ledger digests differ from the corpus")
    assets = manifest.get("assets", [])
    _require(len(assets) == len(rows), "asset ledger does not cover every row")
    by_id = {row["row_id"]: row for row in rows}
    for asset in assets:
        row = by_id.get(asset.get("row_id"))
        _require(row is not None, "asset ledger references an unknown row")
        _require(asset["image_sha256"] == row["root_asset"]["image_sha256"],
                 "asset ledger image digest differs")
        _require(asset["role"] == row["split"]["role"],
                 "asset ledger role differs")
        _require(asset["row_sha256"] == _row_sha256(row),
                 "asset ledger row digest differs")
    row_digests = {row["row_id"]: _row_sha256(row) for row in rows}
    _require(len(row_digests) == len(rows), "normalized row ids are not unique")
    role_counts = Counter(row["split"]["role"] for row in rows)
    for role in ROLES:
        artifact = manifest["artifacts"]["manifests"][role]
        role_path = data_root / artifact["path"]
        _require(role_path.is_file(), f"{role} manifest is missing")
        role_bytes = role_path.read_bytes()
        _require(hashlib.sha256(role_bytes).hexdigest() == artifact["sha256"],
                 f"{role} manifest digest differs")
        role_manifest = json.loads(role_bytes.decode("utf-8"))
        _require(role_manifest.get("format") == MANIFEST_FORMAT,
                 f"{role} manifest format differs")
        _require(role_manifest["role"] == role, f"{role} manifest role differs")
        _require(role_manifest["source_revision"] == manifest["dataset"]["revision"],
                 f"{role} manifest revision differs")
        _require([entry["row_id"] for entry in role_manifest["rows"]]
                 == [row["row_id"] for row in rows if row["split"]["role"] == role],
                 f"{role} manifest rows differ from the corpus")
        _require(role_counts[role] == artifact["rows"],
                 f"{role} row count differs from the manifest")
        _require(artifact.get("sealed") == role_manifest.get("sealed"),
                 f"{role} sealed flag differs from the manifest")
        _require(artifact.get("seal_sha256") == role_manifest.get("seal_sha256"),
                 f"{role} seal digest differs from the manifest")
        for entry in role_manifest["rows"]:
            _require(row_digests.get(entry["row_id"]) == entry["row_sha256"],
                     f"{role} manifest row digest is stale")
        if role == EVAL_ROLE:
            _require(role_manifest.get("sealed") is True
                     and role_manifest.get("untouched") is True,
                     "final-evaluation manifest is not sealed")
            _require(role_manifest["seal_sha256"] == _role_manifest_seal(role_manifest),
                     "final-evaluation seal does not verify")
        else:
            _require(role_manifest.get("sealed") is False,
                     "non-evaluation manifest must not be sealed")
    rejection_path = data_root / manifest["artifacts"]["rejections"]["path"]
    _require(rejection_path.is_file(), "rejection ledger is missing")
    _require(hashlib.sha256(rejection_path.read_bytes()).hexdigest()
             == manifest["artifacts"]["rejections"]["sha256"],
             "rejection ledger digest differs")
    if require_images:
        for row in rows:
            relative = row["observation"]["image_ref"]
            image_path = data_root / "raw" / relative
            _require(image_path.is_file(), f"admitted image is missing: {image_path}")
            _require(sha256_file(image_path) == row["root_asset"]["image_sha256"],
                     f"admitted image digest differs: {image_path}")
    return {"status": "verified", "rows": len(rows), "roles": dict(role_counts),
            "leakage": leakage}


def build_sources(config: Mapping[str, Any]) -> dict[str, RangeSource]:
    """Build HTTPS range sources for the pinned upstream files."""
    dataset = config["dataset"]
    base = dataset.get("source_url")
    _require(isinstance(base, str) and base.startswith("https://"),
             "dataset.source_url must be HTTPS")
    base = base.rstrip("/")
    revision = dataset["revision"]
    files = dataset["files"]
    sources: dict[str, RangeSource] = {
        "card": HttpRangeSource(
            f"{base}/resolve/{revision}/{dataset['card']['path']}",
            size=_card_size(config)),
    }
    for local, upstream in (("annotation", "annotation"), ("metadata", "metadata"),
                            ("images_zip", "images")):
        item = files[upstream]
        sources[local] = HttpRangeSource(
            f"{base}/resolve/{revision}/{item['path']}", size=item["size"])
    return sources


def _card_size(config: Mapping[str, Any]) -> int:
    dataset = config["dataset"]
    _require(isinstance(dataset["card"].get("size"), int) and dataset["card"]["size"] > 0,
             "dataset.card.size is required to bound the card read")
    return dataset["card"]["size"]
