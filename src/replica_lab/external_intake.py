def normalize_text(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def normalize_prompt(value: str) -> str:
    return normalize_text(value.replace(IMAGE_TOKEN, " "))


def normalize_caption(value: str) -> str:
    caption = normalize_text(value)
    if IMAGE_TOKEN in caption:
        raise AssetRejected("caption_contains_image_token",
                            "caption still contains the image placeholder")
    return caption


def _conversation(row: Mapping[str, Any]) -> tuple[str, str]:
    conversations = row.get("conversations")
    if not isinstance(conversations, list) or len(conversations) < 2:
        raise AssetRejected("annotation_bad_conversation",
                            "conversations must contain a prompt and an answer")
    human, gpt = conversations[0], conversations[1]
    if not isinstance(human, dict) or not isinstance(gpt, dict):
        raise AssetRejected("annotation_bad_conversation", "conversation turns must be objects")
    if human.get("from") != "human" or gpt.get("from") != "gpt":
        raise AssetRejected("annotation_bad_conversation",
                            "conversation roles must be human then gpt")
    prompt, answer = human.get("value"), gpt.get("value")
    if not isinstance(prompt, str) or not isinstance(answer, str):
        raise AssetRejected("annotation_bad_conversation", "conversation values must be strings")
    return prompt, answer


def _metadata_index(meta_rows: Sequence[Mapping[str, Any]]) -> dict[str, dict[str, Any]]:
    index: dict[str, dict[str, Any]] = {}
    for row in meta_rows:
        if not isinstance(row, dict):
            continue
        identifier = row.get("id")
        if isinstance(identifier, str) and identifier and identifier not in index:
            index[identifier] = row
    return index


def _forbidden_patterns(config: Mapping[str, Any]) -> list[re.Pattern[str]]:
    return [re.compile(pattern, re.IGNORECASE)
            for pattern in config["admission"]["forbidden_url_patterns"]]


def _candidate_rows(annotation_rows: Sequence[Mapping[str, Any]],
                    meta_rows: Sequence[Mapping[str, Any]],
                    zip_entries: Mapping[str, Any],
                    config: Mapping[str, Any],
                    rejections: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Filter metadata candidates and record every exclusion with its reason."""
    meta_by_id = _metadata_index(meta_rows)
    forbidden = _forbidden_patterns(config)
    preprocessing = config["preprocessing"]
    candidates: list[dict[str, Any]] = []
    for index, row in enumerate(annotation_rows):
        identifier = row.get("id") if isinstance(row, dict) else None
        image_path = row.get("image") if isinstance(row, dict) else None
        rejection = None
        if not isinstance(identifier, str) or not identifier:
            rejection = ("annotation_missing_fields", "annotation id is missing")
        elif not isinstance(image_path, str) or not UPSTREAM_IMAGE_PATTERN.fullmatch(image_path):
            rejection = ("upstream_image_path_invalid",
                         f"unexpected upstream image path {image_path!r}")
        if rejection is None:
            try:
                prompt, answer = _conversation(row)
                prompt = normalize_prompt(prompt)
                caption = normalize_caption(answer)
            except AssetRejected as error:
                rejection = (error.code, error.detail)
        if rejection is None:
            if not prompt:
                rejection = ("prompt_empty", "prompt is empty after normalization")
            elif any(pattern.search(image_path) for pattern in forbidden) or \
                    any(pattern.search(str(meta_by_id.get(identifier, {}).get("url", "")))
                        for pattern in forbidden):
                rejection = ("upstream_url_forbidden",
                             "upstream asset matches a reserved/blocked family term")
            elif len(caption) < preprocessing["min_caption_chars"]:
                rejection = ("caption_too_short", f"caption has {len(caption)} characters")
            elif len(caption) > preprocessing["max_caption_chars"]:
                rejection = ("caption_too_long", f"caption has {len(caption)} characters")
            elif caption.casefold() in prompt.casefold():
                rejection = ("label_in_prompt", "gold caption appears in the prompt")
        meta = meta_by_id.get(identifier) if isinstance(identifier, str) else None
        if rejection is None:
            if meta is None:
                rejection = ("metadata_missing", "no metadata row matches the annotation id")
            elif meta.get("image") != image_path:
                rejection = ("metadata_image_mismatch",
                             f"metadata image {meta.get('image')!r} differs")
        if rejection is None:
            url = meta.get("url")
            if not isinstance(url, str) or not re.match(r"^https?://[^/\s]+", url):
                rejection = ("upstream_url_missing", "upstream URL is missing or invalid")
        if rejection is None:
            if image_path not in zip_entries:
                rejection = ("zip_member_missing", f"{image_path} is absent from images.zip")
        if rejection is not None:
            rejections.append({"format": REJECTION_FORMAT, "stage": "metadata",
                               "reason": rejection[0], "detail": rejection[1],
                               "source_row_index": index,
                               "root_image_id": f"{config['dataset']['id']}:{identifier}",
                               "upstream_image_path": image_path if isinstance(image_path, str) else None})
            continue
        blip = meta.get("blip_caption")
        candidates.append({
            "annotation_index": index,
            "root_image_id": f"{config['dataset']['id']}:{identifier}",
            "upstream_id": identifier,
            "upstream_image_path": image_path,
            "upstream_url": meta["url"],
            "prompt": prompt,
            "caption": caption,
            "blip_caption_sha256": sha256_text(blip) if isinstance(blip, str) else None,
            "blip_caption_equals_target": isinstance(blip, str)
            and normalize_text(blip) == caption,
            "rank": sha256_text(f"{config['sampling']['seed']}\x00{identifier}"),
        })
    candidates.sort(key=lambda item: item["rank"])
    # Global duplicate handling is deterministic: the best-ranked occurrence wins.
    seen_urls: dict[str, str] = {}
    seen_captions: dict[str, str] = {}
    seen_roots: dict[str, str] = {}
    unique: list[dict[str, Any]] = []
    for candidate in candidates:
        if candidate["root_image_id"] in seen_roots:
            rejections.append({"format": REJECTION_FORMAT, "stage": "metadata",
                               "reason": "duplicate_root_id",
                               "detail": "root asset already used by "
                                         f"{seen_roots[candidate['root_image_id']]}",
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        if candidate["upstream_url"] in seen_urls:
            rejections.append({"format": REJECTION_FORMAT, "stage": "metadata",
                               "reason": "duplicate_url",
                               "detail": f"URL already used by {seen_urls[candidate['upstream_url']]}",
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        caption_key = candidate["caption"].casefold()
        if caption_key in seen_captions:
            rejections.append({"format": REJECTION_FORMAT, "stage": "metadata",
                               "reason": "duplicate_caption",
                               "detail": "caption already used by "
                                         f"{seen_captions[caption_key]}",
                               "source_row_index": candidate["annotation_index"],
                               "root_image_id": candidate["root_image_id"],
                               "upstream_image_path": candidate["upstream_image_path"]})
            continue
        seen_roots[candidate["root_image_id"]] = candidate["root_image_id"]
        seen_urls[candidate["upstream_url"]] = candidate["root_image_id"]
        seen_captions[caption_key] = candidate["root_image_id"]
        unique.append(candidate)
    rejections.sort(key=lambda item: (item["stage"], item.get("source_row_index", -1),
                                      item["reason"]))
    return unique


