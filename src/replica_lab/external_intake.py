class ExternalIntakeError(ValueError):
    """Intake refused an input or an artifact failed verification."""


class AssetRejected(ExternalIntakeError):
    """One upstream row or asset is ineligible; admission continues elsewhere."""

    def __init__(self, code: str, detail: str):
        super().__init__(f"{code}: {detail}")
        self.code = code
        self.detail = detail


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ExternalIntakeError(message)


def _is_sha256(value: Any) -> bool:
    return isinstance(value, str) and bool(SHA256_PATTERN.fullmatch(value))


def _is_revision(value: Any) -> bool:
    return isinstance(value, str) and bool(REVISION_PATTERN.fullmatch(value))


def _write_exact(path: str | Path, data: bytes) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        _require(path.read_bytes() == data,
                 f"existing artifact differs from regenerated bytes: {path}")
        return
    path.write_bytes(data)


def _write_text_exact(path: str | Path, text: str) -> None:
    _write_exact(path, text.encode("utf-8"))


def _json_text(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True,
                      allow_nan=False) + "\n"


