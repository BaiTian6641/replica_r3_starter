"""Model-neutral operation surface; native implementations must declare their ABI."""
from typing import Protocol
from .contracts import DecisionFrame, MemoryRead, SenseFrame, VisualInput


class BackboneAdapter(Protocol):
    def encode_observations(self, input_ids, valid): ...
    def sense(self, prompt_ids, prompt_mask, *, visual: VisualInput | None = None) -> SenseFrame: ...
    def forward_with_frame(self, input_ids, frame: DecisionFrame, **kwargs): ...
    def generate_action(self, request, **kwargs): ...
